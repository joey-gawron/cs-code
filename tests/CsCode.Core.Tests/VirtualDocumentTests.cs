using CsCode.Core.Platform;
using CsCode.Core.Text;
using CsCode.TestDoubles;
using Xunit;

namespace CsCode.Core.Tests;

/// <summary>Read-only library and generated documents (cscode-virtual:): URIs, titles, the provider registry, the bounded cache, read-only files.</summary>
public class VirtualDocumentTests
{
    private static CancellationToken Ct => TestContext.Current.CancellationToken;

    private sealed class Provider(string name, Func<Uri, string?> text) : IVirtualDocumentProvider
    {
        public int Calls;
        public string Name => name;
        public ValueTask<VirtualDocumentContent?> ProvideAsync(Uri uri, CancellationToken ct)
        {
            Interlocked.Increment(ref Calls);
            return ValueTask.FromResult(text(uri) is { } t ? new VirtualDocumentContent(t) : null);
        }
    }

    [Fact]
    public void A_virtual_uri_names_its_provider_kind_and_file_and_titles_the_tab()
    {
        var uri = VirtualDocumentUri.Create("lsp", VirtualDocumentKinds.Decompiled, "1a", "String.cs");
        Assert.Equal("cscode-virtual://lsp/decompiled/1a/String.cs", uri.ToString());
        Assert.True(VirtualDocumentUri.TryParse(uri, out var provider, out var kind, out var id, out var name));
        Assert.Equal(("lsp", "decompiled", "1a", "String.cs"), (provider, kind, id, name));
        Assert.Equal("String.cs [decompiled]", VirtualDocumentUri.Title(uri));
        Assert.Equal("Dictionary`2+Enumerator.cs [library source]",
            VirtualDocumentUri.Title(VirtualDocumentUri.Create("lsp", VirtualDocumentKinds.Source, "2", "Dictionary`2+Enumerator.cs")));
        Assert.False(VirtualDocumentUri.IsVirtual(new Uri("file:///w/String.cs")));
    }

    [Fact]
    public async Task Documents_are_read_only_files_of_their_scheme_served_by_their_provider()
    {
        var service = new VirtualDocumentService();
        var known = VirtualDocumentUri.Create("lsp", VirtualDocumentKinds.Generated, "1", "Gen.g.cs");
        var provider = new Provider("lsp", u => u == known ? "// <auto-generated/>\nclass G { }" : null);
        using (service.Register(provider))
        {
            var stat = await service.StatAsync(known, Ct);
            Assert.NotNull(stat);
            Assert.True(stat.IsReadOnly);
            Assert.Equal("// <auto-generated/>\nclass G { }", System.Text.Encoding.UTF8.GetString(await service.ReadFileAsync(known, Ct)));
            Assert.Equal(1, provider.Calls); // stat then read: one request, the second answer from the cache
            await Assert.ThrowsAsync<UnauthorizedAccessException>(() => service.WriteFileAsync(known, new byte[] { 1 }, ct: Ct).AsTask());
            await Assert.ThrowsAsync<UnauthorizedAccessException>(() => service.DeleteAsync(known, ct: Ct).AsTask());
            Assert.Null(await service.StatAsync(VirtualDocumentUri.Create("lsp", VirtualDocumentKinds.Generated, "9", "Gone.cs"), Ct));
            await Assert.ThrowsAsync<FileNotFoundException>(() => service.ReadFileAsync(VirtualDocumentUri.Create("other", "x", "1", "A.cs"), Ct).AsTask());
        }
        Assert.Equal(0, service.CachedCount); // unregistering drops what it served
        Assert.Null(await service.GetAsync(known, Ct));
    }

    [Fact]
    public async Task The_cache_is_bounded_by_count_and_size()
    {
        var service = new VirtualDocumentService();
        using var _ = service.Register(new Provider("lsp", u => new string('x', 1024 * 1024)));
        for (var i = 0; i < 40; i++) await service.GetAsync(VirtualDocumentUri.Create("lsp", "decompiled", i.ToString(), "A.cs"), Ct);
        Assert.True(service.CachedCount <= 8, $"{service.CachedCount} documents of 1 M characters cached (8 M at most)");
    }

    [Fact]
    public void A_registered_provider_is_not_retained_after_its_registration_is_disposed()
    {
        var service = new VirtualDocumentService();
        LeakAssert.NotRetained(() =>
        {
            var provider = new Provider("lsp", u => "text");
            service.Register(provider).Dispose();
            return [provider];
        });
    }

    [Fact]
    public void Core_registers_the_service_as_the_scheme_file_system()
    {
        var services = new Microsoft.Extensions.DependencyInjection.ServiceCollection();
        services.AddCsCodeCore();
        Assert.Contains(services, d => d.ServiceType == typeof(IVirtualDocumentService));
        Assert.Contains(services, d => d.ServiceType == typeof(IFileSystemProvider));
    }
}
