//! The Linux menu bar (File, Edit, Selection, Find, View, Goto, Tools, ...).

const Action = @import("../settings/keymap.zig").Action;

pub const Item = union(enum) {
    action: struct { caption: []const u8, action: Action },
    /// A right-click menu entry that acts on what was clicked (see
    /// context_menu.zig) rather than on the active view.
    command: struct { caption: []const u8, command: Command },
    separator,

    pub fn caption(item: Item) []const u8 {
        return switch (item) {
            .action => |x| x.caption,
            .command => |x| x.caption,
            .separator => "",
        };
    }
};

/// What `Item.command` entries do; context_menu.run carries them out.
pub const Command = enum {
    copy_path,
    copy_relative_path,
    reveal_in_os,
    open_externally,
    new_terminal_here,
    find_in_folder,
    close_tabs_to_right,
    git_stage,
    git_unstage,
    git_discard,
    git_open,
};

pub const Menu = struct {
    title: []const u8,
    items: []const Item,
};

fn a(caption: []const u8, action: Action) Item {
    return .{ .action = .{ .caption = caption, .action = action } };
}
const sep: Item = .separator;

